def inside(x,y,polygon):
    result=False
    for (a,b),(c,d) in zip(polygon,polygon[1:]+polygon[:1]):
        if (b>y+.5)!=(d>y+.5) and x+.5<(c-a)*(y+.5-b)/(d-b)+a:result=not result
    return result

def main():
    sources={}
    with tempfile.TemporaryDirectory() as folder:
        for name in sorted({room for room,_ in OBJECTS.values()}):
            webp=Path(folder)/(name+".webp");png=Path(folder)/(name+".png")
            webp.write_bytes(subprocess.check_output(["git","show",REV+":internal/frontend/app/assets/pixel-jijia/interior-"+name+"-v6.webp"],cwd=ROOT))
            subprocess.run(["sips","-s","format","png",str(webp),"--out",str(png)],check=True,stdout=subprocess.DEVNULL)
            _,_,sources[name]=ground.read_rgb_png(png)
    W,H=1024,768
    atlas=bytearray(W*H*4);mapping={};x=2;y=2;row_h=0
    for key,(name,polys) in OBJECTS.items():
        xs=[a for poly in polys for a,b in poly];ys=[b for poly in polys for a,b in poly]
        a,b,c,d=min(xs),min(ys),max(xs)+1,max(ys)+1
        w,h=c-a,d-b
        if x+w+2>W:x=2;y+=row_h+4;row_h=0
        if y+h+2>H:raise ValueError("atlas overflow")
        for j in range(h):
            for i in range(w):
                if not any(inside(a+i,b+j,poly) for poly in polys):continue
                rgb=ground.pixel(sources[name],600,a+i,b+j)
                at=((y+j)*W+x+i)*4;atlas[at:at+4]=rgb+b"\xff"
        mapping[key]=[x,y,w,h];x+=w+4;row_h=max(h,row_h)
    raw=b"".join(b"\0"+atlas[y*W*4:(y+1)*W*4] for y in range(H))
    png=b"\x89PNG\r\n\x1a\n"+ground.chunk(b"IHDR",struct.pack(">IIBBBBB",W,H,8,6,0,0,0))+ground.chunk(b"IDAT",zlib.compress(raw,9))+ground.chunk(b"IEND",b"")
    (DEST/"room-props-v3.png").write_bytes(png)
    (DEST/"room-props-v3.json").write_text(json.dumps(mapping,indent=2)+"\n")
    print(f"{len(mapping)} independent sprites, {W}×{H}, {len(png)} bytes")
if __name__=="__main__":main()
