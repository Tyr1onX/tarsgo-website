#!/usr/bin/env python3
"""Generate list thumbnails; preserve certificate originals. Requires Pillow."""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public/assets/images/CertificateOfAchievement"
OUTPUT = SOURCE / "Thumbnails"
OUTPUT.mkdir(exist_ok=True)
assets = {}
for source in sorted(SOURCE.glob("certificate-*.webp")):
    with Image.open(source) as opened:
        image = ImageOps.exif_transpose(opened).convert("RGB")
        image.thumbnail((640, 640), Image.Resampling.LANCZOS)
        temporary = OUTPUT / f"{source.stem}.webp"
        if max(opened.size) <= 640:
            temporary.write_bytes(source.read_bytes())
        else:
            image.save(temporary, "WEBP", quality=84, method=6)
        fingerprint = hashlib.sha256(temporary.read_bytes()).hexdigest()[:8]
        filename = f"{source.stem}-{fingerprint}.webp"
        temporary.replace(OUTPUT / filename)
        assets[source.stem] = f"/assets/images/CertificateOfAchievement/Thumbnails/{filename}"
(ROOT / "internal/frontend/app/lib/honor-material-thumbnails.ts").write_text(
    "// Generated by scripts/optimize_honor_thumbnails.py.\nexport const honorMaterialThumbnails: Record<string, string> = "
    + json.dumps(assets, ensure_ascii=False, indent=2) + ";\n"
)

for path in OUTPUT.glob("certificate-*.webp"):
    if path.name not in {Path(src).name for src in assets.values()}:
        path.unlink()
